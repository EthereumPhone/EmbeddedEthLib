w("""/-! ## The sponge for Keccak-256 -/

def zeros136 : ByteArray := ⟨Array.replicate 136 0⟩

/-- `pad RATE msg` built with byte-array copies instead of a boxed `Array UInt8`. -/
def padF (msg : ByteArray) : ByteArray :=
  let k := RATE - msg.size % RATE
  let b := (ByteArray.emptyWithCapacity (msg.size + k)).append msg
  let b := zeros136.copySlice 0 b b.size k
  let b := b.set! msg.size (b.get! msg.size ||| 0x01)
  b.set! (b.size - 1) (b.get! (b.size - 1) ||| 0x80)

/-- Absorb `n` blocks of 136 bytes from `p` on, the permutation `f` after each. -/
@[specialize] def absorbF (f : State → State) (bytes : @& ByteArray) : Nat → Nat → State → State
  | 0, _, S => S
  | n + 1, p, S =>
    let l := fun (k : Nat) => Internal.laneAt bytes (p + 8 * k)
    let S' : State := ⟨S.a0 ^^^ l 0, S.a1 ^^^ l 1, S.a2 ^^^ l 2, S.a3 ^^^ l 3, S.a4 ^^^ l 4,
      S.a5 ^^^ l 5, S.a6 ^^^ l 6, S.a7 ^^^ l 7, S.a8 ^^^ l 8, S.a9 ^^^ l 9, S.a10 ^^^ l 10,
      S.a11 ^^^ l 11, S.a12 ^^^ l 12, S.a13 ^^^ l 13, S.a14 ^^^ l 14, S.a15 ^^^ l 15,
      S.a16 ^^^ l 16, S.a17, S.a18, S.a19, S.a20, S.a21, S.a22, S.a23, S.a24⟩
    absorbF f bytes n (p + 136) (f S')

/-- The 32 digest bytes of lanes 0 to 3, least significant first, in one array. -/
def squeezeF (S : State) : Vector UInt8 DIGEST_LEN :=
  let a := S.a0; let b := S.a1; let c := S.a2; let d := S.a3
  ⟨#[a.toUInt8, (a >>> 8).toUInt8, (a >>> 16).toUInt8, (a >>> 24).toUInt8,
     (a >>> 32).toUInt8, (a >>> 40).toUInt8, (a >>> 48).toUInt8, (a >>> 56).toUInt8,
     b.toUInt8, (b >>> 8).toUInt8, (b >>> 16).toUInt8, (b >>> 24).toUInt8,
     (b >>> 32).toUInt8, (b >>> 40).toUInt8, (b >>> 48).toUInt8, (b >>> 56).toUInt8,
     c.toUInt8, (c >>> 8).toUInt8, (c >>> 16).toUInt8, (c >>> 24).toUInt8,
     (c >>> 32).toUInt8, (c >>> 40).toUInt8, (c >>> 48).toUInt8, (c >>> 56).toUInt8,
     d.toUInt8, (d >>> 8).toUInt8, (d >>> 16).toUInt8, (d >>> 24).toUInt8,
     (d >>> 32).toUInt8, (d >>> 40).toUInt8, (d >>> 48).toUInt8, (d >>> 56).toUInt8], rfl⟩

@[inline] def keccak256With (f : State → State) (msg : ByteArray) : Vector UInt8 DIGEST_LEN :=
  let padded := padF msg
  squeezeF (absorbF f padded (padded.size / RATE) 0 State.zero)

/-- Keccak-256 with the one-round-per-call permutation. -/
def keccak256F1 (msg : ByteArray) : Vector UInt8 DIGEST_LEN := keccak256With keccakF1 msg
/-- Keccak-256 with the two-rounds-per-call permutation. -/
def keccak256F2 (msg : ByteArray) : Vector UInt8 DIGEST_LEN := keccak256With keccakF2 msg
/-- Keccak-256 with the unrolled permutation. -/
def keccak256FU (msg : ByteArray) : Vector UInt8 DIGEST_LEN := keccak256With keccakFU msg
/-- EthLib's sponge with the one-round-per-call permutation (isolates the sponge cost). -/
def keccak256SpecSponge1 (msg : ByteArray) : Vector UInt8 DIGEST_LEN :=
  Internal.squeeze (spongeAbsorb keccakF1 RATE msg)
""")
w("""/-! ## A sponge that reads lanes without bounds checks or `Nat` arithmetic -/

theorem idx_lt {p s : Nat} (h : p + 136 ≤ s) (c : Nat) (hc : c < 136) :
    (USize.ofNat p + USize.ofNat c).toNat < s := by
  rw [USize.toNat_add]
  have h1 := Nat.mod_le ((USize.ofNat p).toNat + (USize.ofNat c).toNat) (2 ^ System.Platform.numBits)
  have h2 : (USize.ofNat p).toNat ≤ p := by rw [USize.toNat_ofNat']; exact Nat.mod_le _ _
  have h3 : (USize.ofNat c).toNat ≤ c := by rw [USize.toNat_ofNat']; exact Nat.mod_le _ _
  omega

/-- Byte `c` of the block at `p`, as a `UInt32`, read in place. -/
@[inline] def rdb (bytes : @& ByteArray) (p : Nat) (h : p + 136 ≤ bytes.size) (q : USize)
    (hq : q = USize.ofNat p) (c : Nat) (hc : c < 136) : UInt32 :=
  (bytes.uget (q + USize.ofNat c) (hq ▸ idx_lt h c hc)).toUInt32

/-- The little-endian word of bytes `c` to `c + 3` of the block at `p`. -/
@[inline] def lane32 (bytes : @& ByteArray) (p : Nat) (h : p + 136 ≤ bytes.size) (q : USize)
    (hq : q = USize.ofNat p) (c : Nat) (hc : c + 4 ≤ 136) : UInt32 :=
  rdb bytes p h q hq c (by omega) ||| rdb bytes p h q hq (c + 1) (by omega) <<< 8 |||
    rdb bytes p h q hq (c + 2) (by omega) <<< 16 ||| rdb bytes p h q hq (c + 3) (by omega) <<< 24

/-- Lane `c / 8` of the block at `p`: `Internal.laneAt bytes (p + c)`. -/
@[inline] def lane64 (bytes : @& ByteArray) (p : Nat) (h : p + 136 ≤ bytes.size) (q : USize)
    (hq : q = USize.ofNat p) (c : Nat) (hc : c + 8 ≤ 136) : UInt64 :=
  (lane32 bytes p h q hq c (by omega)).toUInt64 |||
    (lane32 bytes p h q hq (c + 4) (by omega)).toUInt64 <<< 32

/-- Absorb `n` blocks of 136 bytes from `p` on, the permutation `f` after each. -/
@[specialize] def absorbG (f : State → State) (bytes : @& ByteArray) :
    (n p : Nat) → p + 136 * n ≤ bytes.size → State → State
  | 0, _, _, S => S
  | n + 1, p, hp, S =>
    have h : p + 136 ≤ bytes.size := by omega
    let q := USize.ofNat p
    absorbG f bytes n (p + 136) (by omega) (f ⟨
      S.a0 ^^^ lane64 bytes p h q rfl 0 (by decide),
      S.a1 ^^^ lane64 bytes p h q rfl 8 (by decide),
      S.a2 ^^^ lane64 bytes p h q rfl 16 (by decide),
      S.a3 ^^^ lane64 bytes p h q rfl 24 (by decide),
      S.a4 ^^^ lane64 bytes p h q rfl 32 (by decide),
      S.a5 ^^^ lane64 bytes p h q rfl 40 (by decide),
      S.a6 ^^^ lane64 bytes p h q rfl 48 (by decide),
      S.a7 ^^^ lane64 bytes p h q rfl 56 (by decide),
      S.a8 ^^^ lane64 bytes p h q rfl 64 (by decide),
      S.a9 ^^^ lane64 bytes p h q rfl 72 (by decide),
      S.a10 ^^^ lane64 bytes p h q rfl 80 (by decide),
      S.a11 ^^^ lane64 bytes p h q rfl 88 (by decide),
      S.a12 ^^^ lane64 bytes p h q rfl 96 (by decide),
      S.a13 ^^^ lane64 bytes p h q rfl 104 (by decide),
      S.a14 ^^^ lane64 bytes p h q rfl 112 (by decide),
      S.a15 ^^^ lane64 bytes p h q rfl 120 (by decide),
      S.a16 ^^^ lane64 bytes p h q rfl 128 (by decide),
      S.a17, S.a18, S.a19, S.a20, S.a21, S.a22, S.a23, S.a24⟩)

@[inline] def keccak256GWith (f : State → State) (msg : ByteArray) : Vector UInt8 DIGEST_LEN :=
  let padded := padF msg
  squeezeF (absorbG f padded (padded.size / 136) 0
    (by have := Nat.mul_div_le padded.size 136; omega) State.zero)

/-- Keccak-256: in-place lane reads, one round per tail call. -/
def keccak256G1 (msg : ByteArray) : Vector UInt8 DIGEST_LEN := keccak256GWith keccakF1 msg
/-- Keccak-256: in-place lane reads, two rounds per tail call. -/
def keccak256G2 (msg : ByteArray) : Vector UInt8 DIGEST_LEN := keccak256GWith keccakF2 msg
/-- Keccak-256: in-place lane reads, unrolled permutation. -/
def keccak256GU (msg : ByteArray) : Vector UInt8 DIGEST_LEN := keccak256GWith keccakFU msg
""")
w("end EthLib.Cryptography.Hash.Keccak.Fast")
