# genvec.py <tests/cryptography/sphincs> [out.c]: embed the leanSPHINCS known-answer vectors as one volatile byte blob: pk(32) | msg(32) | sig(7740) | seed(32).
import re, sys
T = sys.argv[1]; OUT = sys.argv[2] if len(sys.argv) > 2 else 'vec.c'
def field(path, name):
    s = open(path).read()
    m = re.search(r"^\s*%s:\s*'0x([0-9a-f]*)'" % name, s, re.M)
    return bytes.fromhex(m.group(1))
v = T + '/verify/verify_valid_known_answer/data.yaml'
pk, msg, sig = field(v, 'public_key'), field(v, 'message'), field(v, 'signature')
kg = T + '/key_gen/key_gen_known_answer/data.yaml'
seed, pk2 = field(kg, 'seed'), field(kg, 'output')
sg = T + '/sign/sign_known_answer/data.yaml'
seed3, msg3, sig3 = field(sg, 'seed'), field(sg, 'message'), field(sg, 'output')
assert pk == pk2 and seed == seed3 and msg == msg3 and sig == sig3, 'vectors disagree'
assert len(pk) == 32 and len(msg) == 32 and len(sig) == 7740 and len(seed) == 32
blob = pk + msg + sig + seed
with open(OUT, 'w') as f:
    f.write('/* Generated by genvec.py from EthLib tests/cryptography/sphincs known answers. */\n#include <stdint.h>\n')
    f.write('volatile const uint8_t pq_vec[%d] = {\n' % len(blob))
    for i in range(0, len(blob), 24):
        f.write('  ' + ','.join('0x%02x' % b for b in blob[i:i+24]) + ',\n')
    f.write('};\n')
print('pk', pk.hex()); print('counters bottom/middle/top:',
  [int.from_bytes(sig[o:o+4], 'big') for o in (16 + 4224, 16 + 4224 + 1156, 16 + 4224 + 2 * 1156)])
print('sig[0:64]', sig[:64].hex())
